import { CriterionStatus, ResearchResponse } from '../types/api';

const STATUS_TEXT: Record<CriterionStatus, string> = {
  met: 'met',
  not_met: 'NOT met',
  missing: 'no data',
  predicted_met: 'predicted to meet (ML estimate)',
  predicted_not_met: 'predicted not to meet (ML estimate)',
  unverified: 'cannot be verified',
};

function num(value: number | null, unit: string): string {
  if (value === null) return 'n/a';
  const text = Math.abs(value) > 0 && Math.abs(value) < 0.01 ? value.toExponential(2) : String(Math.round(value * 1e4) / 1e4);
  return `${text} ${unit}`.trim();
}

/** The full report as Markdown: what was asked, what ran, what was found, and how solid it is. */
export function buildResearchMarkdown(result: ResearchResponse, now = new Date()): string {
  const lines: string[] = [];
  const push = (...l: string[]) => lines.push(...l, '');

  push('# CrucibleAI Research Report');
  push(
    `**Query**: "${result.query}"  `,
    `**Session**: \`${result.session_id}\`  `,
    `**Date**: ${now.toISOString()}  `,
    `**Duration**: ${(result.duration_ms / 1000).toFixed(1)}s, ${result.retrieval_attempts} retrieval pass(es)  `,
    `**Mode**: ${result.mode.llm ? `LLM ${result.mode.llm}` : `no LLM (heuristic mode${result.mode.llm_unavailable_reason ? `: ${result.mode.llm_unavailable_reason}` : ''})`}; materials data: ${
      result.mode.materials_project === 'live' ? 'Materials Project (live)' : 'offline reference table'
    }`,
  );

  if (result.warnings.length > 0) {
    push('## Warnings', ...result.warnings.map((w) => `- ${w}`));
  }

  push('## Summary', `> ${result.hypothesis}`);

  push('## Criteria', ...(result.criteria.length ? result.criteria.map((c) => `- ${c.label}`) : ['_No criteria could be parsed._']));

  push('## Ranked candidates');
  if (result.candidates.length === 0) {
    push('_No candidates found._');
  } else {
    for (const c of result.candidates) {
      const name = c.formula ?? c.name;
      push(
        `### ${c.rank}. ${name}: ${c.status} (score ${c.score.toFixed(2)}${c.origin === 'database' ? ', database only' : ''})`,
        ...c.criteria.map(
          (r) => `- ${r.label}: **${STATUS_TEXT[r.status]}**${r.value !== null ? `, ${num(r.value, r.unit)}` : ''}${r.detail ? ` (${r.detail})` : ''}`,
        ),
        ...(c.flags.length ? [`- Flags: ${c.flags.join(', ')}`] : []),
      );
    }
  }

  push('## Hypotheses');
  if (result.hypotheses.length === 0) push('_None could be generated from the available evidence._');
  result.hypotheses.forEach((h, i) => {
    push(
      `### H${i + 1} (${h.confidence} confidence${h.origin === 'template' ? ', template' : ''}${h.grounded === false ? ', NOT supported by its evidence' : ''})`,
      h.statement,
      `**Evidence**: ${h.evidence.length ? h.evidence.map((e) => e.id).join(', ') : 'none'}  `,
      `**Suggested experiment**: ${h.suggested_experiment}`,
    );
  });
  push(
    `_Grounding check (${result.grounding.method}): ${result.grounding.checked - result.grounding.unsupported} of ${result.grounding.checked} hypotheses supported._`,
  );

  push('## Knowledge gaps', ...(result.knowledge_gaps.length ? result.knowledge_gaps.map((g) => `- ${g}`) : ['_None detected._']));

  push(
    '## References',
    ...result.citations.map(
      (c) => `- [${c.id}] ${c.title}${c.authors ? `, ${c.authors}` : ''}${c.year ? ` (${c.year})` : ''}${c.url ? ` <${c.url}>` : ''}`,
    ),
  );

  push('---', '_Generated by CrucibleAI. Predicted values are machine-learning estimates, not measurements._');
  return lines.join('\n');
}

export function exportResearchMarkdown(result: ResearchResponse): void {
  const stamp = new Date().toISOString().split('T')[0];
  downloadFile(`CrucibleAI_Research_${result.session_id.slice(0, 8)}_${stamp}.md`, buildResearchMarkdown(result), 'text/markdown');
}

export function exportResearchJSON(result: ResearchResponse): void {
  const stamp = new Date().toISOString().split('T')[0];
  downloadFile(
    `CrucibleAI_Dataset_${result.session_id.slice(0, 8)}_${stamp}.json`,
    JSON.stringify(result, null, 2),
    'application/json',
  );
}

function downloadFile(filename: string, content: string, contentType: string): void {
  const blob = new Blob([content], { type: contentType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
